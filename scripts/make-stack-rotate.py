TIME = '''// Scene clock: the animation runs over 2 s of scene time, mapped onto progress 0..1.
const SCENE_SPAN: f32 = 2.0;
const STEPS: f32 = 120.0;

fn scene_time() -> f32 { return clamp(params.progress, 0.0, 1.0) * SCENE_SPAN - 0.00001; }

// Nothing to draw at the ends: the last pass shows the plain clips there.
fn idle() -> bool { return params.progress <= 0.0 || params.progress >= 1.0; }

// Linear lookup in a baked curve table (STEPS + 1 rows over the scene span).
fn at(tab: array<vec4f, 121>, t: f32) -> vec4f {
    let f = clamp(t / SCENE_SPAN, 0.0, 1.0) * STEPS;
    let i = min(u32(floor(f)), 119u);
    return mix(tab[i], tab[i + 1u], f - f32(i));
}
'''

PROJECT = '''// Scene units: a 672 x 504 design frame stretched over the output, camera with a 39.6 degree
// horizontal field of view that frames the z = 0 plane exactly.
const DESIGN = vec2f(672.0, 504.0);
const FOV_X: f32 = 39.5977527;
const DEG: f32 = 0.0174532925;

fn spin_z(v: vec3f, deg: f32) -> vec3f {
    let a = -deg * DEG;
    let c = cos(a);
    let s = sin(a);
    return vec3f(v.x * c - v.y * s, v.x * s + v.y * c, v.z);
}

fn spin_y(v: vec3f, deg: f32) -> vec3f {
    let a = -deg * DEG;
    let c = cos(a);
    let s = sin(a);
    return vec3f(v.x * c + v.z * s, v.y, -v.x * s + v.z * c);
}

// Where screen point `uv` lands on a card: returns (u, v, hit). The card hangs from a shared rig
// (uniform scale `rig.x` percent, roll `rig.z` degrees) placed at the frame centre; `place` holds the
// card offset from the rig in design pixels (x right, y down, z away) and its yaw, `roll` its own
// roll, `size` its scale in percent and `pivot` its anchor in design pixels.
fn card_hit(uv: vec2f, rig: vec4f, place: vec4f, roll: f32, size: vec2f, pivot: vec2f) -> vec3f {
    let r = globals.size.x / globals.size.y;
    let unit = vec3f(2.0 * r / DESIGN.x, -2.0 / DESIGN.y, -2.0 * r / DESIGN.x);
    let k = vec3f(size * 0.01, 1.0);
    let lift = vec3f(-(pivot.x / DESIGN.x - 0.5) * 2.0 * r, -(0.5 - pivot.y / DESIGN.y) * 2.0, 0.0);
    let rk = vec3f(rig.x * 0.01, rig.y * 0.01, 1.0);
    let o = spin_z(rk * (place.xyz * unit + spin_y(spin_z(k * lift, roll), place.w)), rig.z);
    let ax = spin_z(rk * spin_y(spin_z(k * vec3f(r, 0.0, 0.0), roll), place.w), rig.z);
    let ay = spin_z(rk * spin_y(spin_z(k * vec3f(0.0, 1.0, 0.0), roll), place.w), rig.z);
    let eye = vec3f(0.0, 0.0, r / tan(0.5 * FOV_X * DEG));
    let ray = vec3f((2.0 * uv.x - 1.0) * r, 1.0 - 2.0 * uv.y, 0.0) - eye;
    // Solve o + a * ax + b * ay = eye + t * ray.
    let rhs = eye - o;
    let det = dot(ax, cross(ay, -ray));
    if (abs(det) < 1e-9) { return vec3f(0.0); }
    let a = dot(rhs, cross(ay, -ray)) / det;
    let b = dot(ax, cross(rhs, -ray)) / det;
    let t = dot(ax, cross(ay, rhs)) / det;
    let hit = select(0.0, 1.0, abs(a) <= 1.0 && abs(b) <= 1.0 && t > 0.0);
    return vec3f(0.5 + 0.5 * a, 0.5 - 0.5 * b, hit);
}

// Premultiplied sample of `tex` on a card; zero off the card.
fn card_texel(tex: texture_2d<f32>, h: vec3f) -> vec4f {
    if (h.z < 0.5) { return vec4f(0.0); }
    let c = textureSampleLevel(tex, smp, h.xy, 0.0);
    return vec4f(c.rgb * c.a, c.a);
}

// Heavy darkening grade applied to the clips shown on the side cards.
fn darken(c: vec4f) -> vec4f {
    let g = 1.0 - pow(clamp(1.0 - (c.rgb - vec3f(0.01)), vec3f(0.0), vec3f(1.01)), vec3f(1.0 / 3.5));
    return vec4f(clamp(g, vec3f(0.0), vec3f(1.0)) * c.a, c.a);
}

fn over(top: vec4f, base: vec4f) -> vec4f { return top + base * (1.0 - top.a); }
'''

HALF = '''// The blurs run on a half-size grid stored in the top-left quarter of their textures; the rest of
// those textures is never written nor read.
fn half_cells() -> vec2f { return ceil(0.5 * globals.size); }

// Frame position (0..1) of the centre of half-grid cell `id`.
fn half_uv(id: vec3u) -> vec2f { return (vec2f(id.xy) + 0.5) / (0.5 * globals.size); }

// Bilinear read of a half-grid texture at frame position `uv`, clamped to the written cells.
fn from_half(tex: texture_2d<f32>, uv: vec2f) -> vec4f {
    let lo = 0.5 / globals.size;
    let hi = (half_cells() - 0.5) / globals.size;
    return textureSampleLevel(tex, smp, clamp(0.5 * uv, lo, hi), 0.0);
}
'''

GAUSS = '''// Separable gaussian in gamma-2.2 light. `strength` follows the editor's blur scale (radius is
// strength / 1000 of the reference side), `quality` widens the tap count. `halved` says `tex` is a
// half-grid texture.
fn tap_count(strength: f32, quality: f32) -> f32 {
    var n: f32;
    if (strength <= 30.0) { n = (0.5 * strength + 2.0) * 0.78; } else { n = (0.5 * strength + 10.0) * 0.66; }
    if (n < 2.0) { n = floor(n + 0.5); }
    let q = quality * 2.0 - 1.0;
    var m = q * 2.0 + 1.0;
    if (q < 0.0) { m = pow(10.0, q); }
    return n * m;
}

fn fetch(tex: texture_2d<f32>, uv: vec2f, halved: bool) -> vec4f {
    if (halved) { return from_half(tex, uv); }
    return textureSampleLevel(tex, smp, uv, 0.0);
}

fn gauss_line(tex: texture_2d<f32>, halved: bool, uv: vec2f, axis: vec2f, strength: f32, quality: f32) -> vec4f {
    let c0 = fetch(tex, uv, halved);
    if (strength <= 0.01) { return c0; }
    let side = max(min(globals.size.x, globals.size.y), 0.5 * max(globals.size.x, globals.size.y));
    let reach = side * strength / 1000.0 / dot(globals.size, axis);
    let sigma = reach / 2.5;
    let n = tap_count(strength, quality);
    let stride = reach / max(n, 1e-5);
    var acc = vec4f(pow(c0.rgb, vec3f(2.2)), c0.a);
    var total = 1.0;
    for (var i = 1; i <= 160; i++) {
        let fi = f32(i);
        if (fi > n) { break; }
        let d = fi * stride;
        let w = exp(-0.5 * d * d / (sigma * sigma));
        let pa = uv - axis * d;
        let pb = uv + axis * d;
        if (dot(pa, axis) >= 0.0) {
            let s = fetch(tex, pa, halved);
            acc += vec4f(pow(s.rgb, vec3f(2.2)), s.a) * w;
            total += w;
        }
        if (dot(pb, axis) <= 1.0) {
            let s = fetch(tex, pb, halved);
            acc += vec4f(pow(s.rgb, vec3f(2.2)), s.a) * w;
            total += w;
        }
    }
    let m = acc / total;
    return vec4f(pow(max(m.rgb, vec3f(0.0)), vec3f(1.0 / 2.2)), m.a);
}
'''

