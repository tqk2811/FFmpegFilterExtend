files["twirl.wgsl"] = shader(
    "Stack and rotate, step 10: rotational smear around the centre, then the frame over black.",
    TIME, HALF, table("BLUR_K") + '''

const TAU: f32 = 6.28318531;
const MAX_TAPS: i32 = 128;

// Mirror a coordinate back into 0..1.
fn fold(x: f32) -> f32 {
    let a = abs(x);
    return abs(floor(ceil(a) / 2.0) * 2.0 - a);
}

fn jitter(p: vec2f) -> f32 {
    var q = fract(p * 13.517);
    q += dot(q, q.yx + vec2f(22.541));
    return fract((q.x + q.y) * q.y);
}

// The blurred frame at `uv`: the half-grid blur while the pulse is on, else the sharp stack.
fn hazed(uv: vec2f, sharp: bool) -> vec4f {
    if (sharp) { return textureSampleLevel(stacked, smp, uv, 0.0); }
    return from_half(haze, uv);
}

// Arc blur: taps walk one way around the centre over amount / 200 of a full turn (y-up coordinates,
// aspect-corrected), with up to 128 taps depending on the distance from the centre.
fn arc_blur(uv: vec2f, amount: f32, sharp: bool) -> vec4f {
    let c0 = hazed(uv, sharp);
    if (abs(amount) < 1e-4) { return c0; }
    let k = amount / 200.0;
    let g = vec2f(uv.x, 1.0 - uv.y);
    let reach = length((g - vec2f(0.5)) * k);
    let n = min(800.0 * (sign(reach) * (0.9 * reach + 0.1)) + 5.0, 128.0);
    let step_a = TAU * k / n;
    let aspect = globals.size.x / globals.size.y;
    let shift = 0.5 * (jitter(g) * 2.0 - 1.0) * step_a;
    var acc = c0;
    var total = 1.0;
    for (var i = 1; i <= MAX_TAPS; i++) {
        let fi = f32(i);
        if (fi > n) { break; }
        let a = fi * step_a + shift;
        var p = g - vec2f(0.5);
        p.y /= aspect;
        p = vec2f(cos(a) * p.x - sin(a) * p.y, sin(a) * p.x + cos(a) * p.y);
        p.y *= aspect;
        p += vec2f(0.5);
        if (p.x < 0.0 || p.y < 0.0 || p.x > 1.0 || p.y > 1.0) { p = vec2f(fold(p.x), fold(p.y)); }
        acc += hazed(vec2f(p.x, 1.0 - p.y), sharp);
        total += 1.0;
    }
    return acc / total;
}

''' + MAIN_HEAD + '''    // Exact clips at the ends, so cutting in and out of the transition never jumps.
    if (params.progress <= 0.0) { gpufx_write(id, vec4f(textureSampleLevel(first, smp, uv, 0.0).rgb, 1.0)); return; }
    if (params.progress >= 1.0) { gpufx_write(id, vec4f(textureSampleLevel(second, smp, uv, 0.0).rgb, 1.0)); return; }
    let blur = at(BLUR_K, t);
    let fx = arc_blur(uv, blur.y, blur.x <= 0.01);
    let base = textureSampleLevel(stacked, smp, uv, 0.0);
    let c = fx + base * (1.0 - fx.a);
    gpufx_write(id, vec4f(c.rgb, 1.0));
}
''')

